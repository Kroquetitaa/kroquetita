/** Auxiliary flight volumes from the unbatched Blender exports; no mesh changes. */
import { readFile, writeFile } from 'node:fs/promises'
import { registerHooks } from 'node:module'
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js'
import { Box3, Matrix4 } from 'three'
registerHooks({ resolve(s, c, next) { try { return next(s, c) } catch (e) { if (e.code === 'ERR_MODULE_NOT_FOUND' && s.startsWith('.') && !/\.[a-z]+$/i.test(s)) return next(s + '.ts', c); throw e } } })
const { blenderAssembly } = await import('../src/world/blenderAssembly.ts')
const loader = new GLTFLoader(), boxes = []
for (const [id, district] of Object.entries(blenderAssembly.districts)) {
  if (id === 'transport') continue // the monorail keeps its original animated elevated track
  const bytes = await readFile(new URL(`../art/kroquetita-city-v01/exports/${id}.glb`, import.meta.url))
  const scene = (await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '')).scene
  scene.applyMatrix4(new Matrix4().fromArray(district.matrix)); scene.updateMatrixWorld(true)
  scene.traverse(object => {
    if (!/canopy|beam|roof|header|titleboard|titleplate|nameplate|handrail|midrail|shelf|^Rig_/i.test(object.name)) return
    const bounds = new Box3().setFromObject(object, true)
    if (bounds.isEmpty() || bounds.max.y < 1) return
    boxes.push({ name: object.name, min: bounds.min.toArray().map(n => +n.toFixed(5)), max: bounds.max.toArray().map(n => +n.toFixed(5)) })
  })
}
for (const exhibit of blenderAssembly.exhibits) boxes.push({ name: exhibit.name, min: [...exhibit.bounds.min], max: [...exhibit.bounds.max] })
await writeFile(new URL('../src/game/airObstacles.ts', import.meta.url), '// Generated by scripts/prepare-air-obstacles.mjs from native Blender exports.\nexport const airObstacles = ' + JSON.stringify(boxes, null, 2) + ' as const\n')
console.log(`Generated ${boxes.length} overhead flight volumes`)
